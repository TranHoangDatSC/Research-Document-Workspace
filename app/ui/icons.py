def filesize(value):
    """Human-readable size for templates (binary units, matching the MiB upload limits)."""
    size = float(value or 0)
    for unit in ("B", "KiB", "MiB", "GiB"):
        if size < 1024 or unit == "GiB":
            return f"{int(size)} B" if unit == "B" else f"{size:.1f} {unit}"
        size /= 1024


def fmt_datetime(value):
    """dd/mm/yyyy HH:MM (UTC as stored); non-datetime values pass through unchanged."""
    return value.strftime("%d/%m/%Y %H:%M UTC") if hasattr(value, "strftime") else value


def pretty_json(value):
    """Readable JSON for <pre>. Returns plain str so Jinja autoescape still applies."""
    return json.dumps(value, indent=2, ensure_ascii=False, default=str)
